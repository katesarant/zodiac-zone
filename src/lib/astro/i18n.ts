export function ordinalHouse(house: number, lang: Lang) {
  if (lang === "el") return `${house}ος οίκος`;
  const s = ["th", "st", "nd", "rd"];
  const v = house % 100;
  return `${house}${s[(v - 20) % 10] ?? s[v] ?? s[0]} house`;
}
